"""Respaldo y migración de la metadata en JSON portable.

El JSON no depende del motor: sirve para respaldar, restaurar en otra instancia o migrar la
metadata a otro motor (definiendo METADATA_URL y corriendo `alembic upgrade head` + import).
Las contraseñas de conexiones viajan cifradas: el destino necesita la misma SECRETS_KEY.
"""
from datetime import date, datetime, timezone

from sqlalchemy import DateTime, func, inspect, select, text
from sqlalchemy.orm import Session

from app.models import ALL_TABLES_IN_ORDER

FORMAT = "dbamanager-metadata"
VERSION = 1


def _ser(v):
    if isinstance(v, (datetime, date)):
        return v.isoformat()
    return v


def export_metadata(db: Session) -> dict:
    alembic_rev = None
    try:
        alembic_rev = db.execute(text("SELECT version_num FROM alembic_version")).scalar()
    except Exception:  # noqa: BLE001 - la tabla puede no existir en instalaciones sin alembic
        db.rollback()
    tables = {}
    for model in ALL_TABLES_IN_ORDER:
        cols = [c.key for c in inspect(model).column_attrs]
        rows = db.scalars(select(model)).all()
        tables[model.__tablename__] = [{c: _ser(getattr(r, c)) for c in cols} for r in rows]
    return {
        "format": FORMAT, "version": VERSION, "alembic_revision": alembic_rev,
        "exported_at": datetime.now(timezone.utc).isoformat(), "tables": tables,
    }


def _parse(model, row: dict) -> dict:
    out = {}
    mapper = inspect(model)
    for attr in mapper.column_attrs:
        if attr.key not in row:
            continue
        v = row[attr.key]
        col = attr.columns[0]
        if v is not None and isinstance(col.type, DateTime) and isinstance(v, str):
            v = datetime.fromisoformat(v)
        out[attr.key] = v
    return out


def is_empty(db: Session) -> bool:
    return all(db.scalar(select(func.count()).select_from(m)) == 0 for m in ALL_TABLES_IN_ORDER)


def import_metadata(db: Session, data: dict, replace: bool) -> dict:
    if data.get("format") != FORMAT:
        raise ValueError("El archivo no es un respaldo de DBA Manager")
    if data.get("version") != VERSION:
        raise ValueError(f"Versión de respaldo no soportada: {data.get('version')}")
    if not is_empty(db):
        if not replace:
            raise ValueError("La metadata destino no está vacía; usa replace=true para sobrescribirla")
        for model in reversed(ALL_TABLES_IN_ORDER):
            db.query(model).delete()
        db.flush()
    counts = {}
    for model in ALL_TABLES_IN_ORDER:
        rows = data["tables"].get(model.__tablename__, [])
        for row in rows:
            db.add(model(**_parse(model, row)))
        db.flush()
        counts[model.__tablename__] = len(rows)
    # Seguridad: un respaldo editado no puede activar la ejecución a nadie. Tras restaurar, cada DBA
    # debe volver a activarla para sí mismo.
    from app.models import UserSetting

    for row in db.scalars(select(UserSetting)).all():
        row.can_execute = False
    _reset_identities(db)
    db.commit()
    return counts


def _reset_identities(db: Session) -> None:
    """Ajusta las columnas identidad para que los nuevos IDs no choquen con los importados."""
    dialect = db.bind.dialect.name
    for model in ALL_TABLES_IN_ORDER:
        pk = inspect(model).primary_key[0]
        if pk.identity is None:
            continue
        table = model.__tablename__
        if dialect == "oracle":
            db.execute(text(f"ALTER TABLE {table} MODIFY {pk.name} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)"))
        elif dialect == "postgresql":
            db.execute(text(f"SELECT setval(pg_get_serial_sequence('{table}', '{pk.name}'), "
                            f"COALESCE((SELECT MAX({pk.name}) FROM {table}), 0) + 1, false)"))

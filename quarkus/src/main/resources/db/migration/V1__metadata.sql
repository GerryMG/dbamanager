-- Metadata de DBA Manager (Oracle 12.1+). Solo crea tablas e índices en el propio usuario.

CREATE TABLE app_users (
  username      VARCHAR2(150) NOT NULL,
  sub           VARCHAR2(100),
  full_name     VARCHAR2(200),
  email         VARCHAR2(200),
  roles         VARCHAR2(200),
  last_seen     TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_app_users PRIMARY KEY (username)
);

CREATE TABLE user_settings (
  username               VARCHAR2(150) NOT NULL,
  can_execute            NUMBER(1) DEFAULT 0 NOT NULL,
  can_execute_changed_at TIMESTAMP WITH TIME ZONE,
  can_execute_until      TIMESTAMP WITH TIME ZONE,
  reauth_at              TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_user_settings PRIMARY KEY (username)
);

CREATE TABLE db_connections (
  id                   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  name                 VARCHAR2(100) NOT NULL,
  engine               VARCHAR2(30) DEFAULT 'oracle' NOT NULL,
  environment          VARCHAR2(20) NOT NULL,
  description          VARCHAR2(500),
  host                 VARCHAR2(200) NOT NULL,
  port                 NUMBER(5) NOT NULL,
  service_name         VARCHAR2(200) NOT NULL,
  catalog_user         VARCHAR2(128) NOT NULL,
  catalog_password_enc CLOB,
  exec_user            VARCHAR2(128),
  exec_password_enc    CLOB,
  allow_execution      NUMBER(1) DEFAULT 0 NOT NULL,
  use_tls              NUMBER(1) DEFAULT 0 NOT NULL,
  server_version       VARCHAR2(40),
  required_approvals   NUMBER(2) DEFAULT 1 NOT NULL,
  active               NUMBER(1) DEFAULT 1 NOT NULL,
  created_by           VARCHAR2(150),
  created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_db_connections PRIMARY KEY (id),
  CONSTRAINT uq_db_connections_name UNIQUE (name)
);

CREATE TABLE projects (
  id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  code        VARCHAR2(30) NOT NULL,
  name        VARCHAR2(200) NOT NULL,
  description VARCHAR2(1000),
  owner       VARCHAR2(150),
  active      NUMBER(1) DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_projects PRIMARY KEY (id),
  CONSTRAINT uq_projects_code UNIQUE (code)
);

-- Llaves de seguridad (WebAuthn / FIDO2) de los DBAs. La llave privada nunca sale del
-- dispositivo del DBA; aquí solo queda la pública.
CREATE TABLE dba_keys (
  id                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  username           VARCHAR2(150) NOT NULL,
  label              VARCHAR2(100) NOT NULL,
  credential_id      VARCHAR2(1400) NOT NULL,
  credential_data    CLOB NOT NULL,
  fingerprint        VARCHAR2(64) NOT NULL,
  sign_count         NUMBER(19) DEFAULT 0 NOT NULL,
  status             VARCHAR2(20) NOT NULL,
  is_root            NUMBER(1) DEFAULT 0 NOT NULL,
  rp_id              VARCHAR2(255) NOT NULL,
  origin             VARCHAR2(500) NOT NULL,
  endorsed_by        NUMBER(10),
  endorsed_by_user   VARCHAR2(150),
  endorsement        CLOB,
  created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
  activated_at       TIMESTAMP WITH TIME ZONE,
  last_used_at       TIMESTAMP WITH TIME ZONE,
  revoked_at         TIMESTAMP WITH TIME ZONE,
  revoked_by         VARCHAR2(150),
  CONSTRAINT pk_dba_keys PRIMARY KEY (id),
  CONSTRAINT uq_dba_keys_credential UNIQUE (fingerprint),
  CONSTRAINT fk_dba_keys_endorser FOREIGN KEY (endorsed_by) REFERENCES dba_keys (id)
);
CREATE INDEX ix_dba_keys_user ON dba_keys (username);

CREATE TABLE approver_scopes (
  id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  username      VARCHAR2(150) NOT NULL,
  connection_id NUMBER(10) NOT NULL,
  schema_name   VARCHAR2(128) NOT NULL,
  granted_by    VARCHAR2(150),
  granted_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  key_id        NUMBER(10),
  signature     CLOB,
  CONSTRAINT pk_approver_scopes PRIMARY KEY (id),
  CONSTRAINT uq_approver_scopes UNIQUE (username, connection_id, schema_name),
  CONSTRAINT fk_scopes_connection FOREIGN KEY (connection_id) REFERENCES db_connections (id),
  CONSTRAINT fk_scopes_key FOREIGN KEY (key_id) REFERENCES dba_keys (id)
);

CREATE TABLE change_requests (
  id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  title          VARCHAR2(200) NOT NULL,
  connection_id  NUMBER(10) NOT NULL,
  project_id     NUMBER(10),
  reason         CLOB NOT NULL,
  purpose        CLOB,
  ticket_ref     VARCHAR2(100),
  status         VARCHAR2(30) NOT NULL,
  target_schemas VARCHAR2(1000),
  requested_by   VARCHAR2(150) NOT NULL,
  created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  submitted_at   TIMESTAMP WITH TIME ZONE,
  decided_at     TIMESTAMP WITH TIME ZONE,
  executed_at    TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_change_requests PRIMARY KEY (id),
  CONSTRAINT fk_requests_connection FOREIGN KEY (connection_id) REFERENCES db_connections (id),
  CONSTRAINT fk_requests_project FOREIGN KEY (project_id) REFERENCES projects (id)
);
CREATE INDEX ix_requests_status ON change_requests (status);

CREATE TABLE request_operations (
  id              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  request_id      NUMBER(10) NOT NULL,
  seq             NUMBER(5) NOT NULL,
  op_type         VARCHAR2(40) NOT NULL,
  target_schema   VARCHAR2(128) NOT NULL,
  object_name     VARCHAR2(128),
  payload         CLOB NOT NULL,
  statements      CLOB NOT NULL,
  status          VARCHAR2(20) NOT NULL,
  statements_done NUMBER(5) DEFAULT 0 NOT NULL,
  message         CLOB,
  executed_at     TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_request_operations PRIMARY KEY (id),
  CONSTRAINT fk_operations_request FOREIGN KEY (request_id) REFERENCES change_requests (id)
);
CREATE INDEX ix_operations_request ON request_operations (request_id);



CREATE TABLE approvals (
  id           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  request_id   NUMBER(10) NOT NULL,
  approver     VARCHAR2(150) NOT NULL,
  decision     VARCHAR2(30) NOT NULL,
  comment_text CLOB,
  active       NUMBER(1) DEFAULT 1 NOT NULL,
  content_hash VARCHAR2(64),
  key_id       NUMBER(10),
  signature    CLOB,
  decided_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_approvals PRIMARY KEY (id),
  CONSTRAINT fk_approvals_request FOREIGN KEY (request_id) REFERENCES change_requests (id),
  CONSTRAINT fk_approvals_key FOREIGN KEY (key_id) REFERENCES dba_keys (id)
);
CREATE INDEX ix_approvals_request ON approvals (request_id);

CREATE TABLE request_comments (
  id         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  request_id NUMBER(10) NOT NULL,
  author     VARCHAR2(150) NOT NULL,
  body       CLOB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_request_comments PRIMARY KEY (id),
  CONSTRAINT fk_comments_request FOREIGN KEY (request_id) REFERENCES change_requests (id)
);

CREATE TABLE executions (
  id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  request_id  NUMBER(10) NOT NULL,
  executed_by VARCHAR2(150) NOT NULL,
  mode_       VARCHAR2(20) NOT NULL,
  status      VARCHAR2(20) NOT NULL,
  log         CLOB,
  notes       CLOB,
  key_id      NUMBER(10),
  signature   CLOB,
  started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  finished_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_executions PRIMARY KEY (id),
  CONSTRAINT fk_executions_request FOREIGN KEY (request_id) REFERENCES change_requests (id),
  CONSTRAINT fk_executions_key FOREIGN KEY (key_id) REFERENCES dba_keys (id)
);

CREATE TABLE audit_log (
  id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  at          TIMESTAMP WITH TIME ZONE NOT NULL,
  username    VARCHAR2(150) NOT NULL,
  action      VARCHAR2(60) NOT NULL,
  entity_type VARCHAR2(40) NOT NULL,
  entity_id   VARCHAR2(60),
  details     CLOB,
  ip          VARCHAR2(60),
  CONSTRAINT pk_audit_log PRIMARY KEY (id)
);
CREATE INDEX ix_audit_entity ON audit_log (entity_type, entity_id);

-- Restablecimiento de la llave raíz (si el DBA principal pierde todas sus llaves). Tiene un
-- periodo de espera visible para todos los DBAs, y cualquier DBA principal con llave puede cancelarlo.
CREATE TABLE root_resets (
  id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  requested_by  VARCHAR2(150) NOT NULL,
  reason        CLOB NOT NULL,
  requested_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  effective_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  status        VARCHAR2(20) NOT NULL,
  closed_by     VARCHAR2(150),
  closed_at     TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_root_resets PRIMARY KEY (id)
);
